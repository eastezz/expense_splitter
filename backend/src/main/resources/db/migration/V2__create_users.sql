-- Accounts for the login (step 12): one row per registered user.
-- The password is never stored as text, only as a BCrypt hash (always 60 characters).
-- Emails are saved in lower case by the app, so "Anna@x.de" and "anna@x.de" count as the same.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254)                NOT NULL,
    password_hash VARCHAR(60)                 NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);