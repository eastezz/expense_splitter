-- Creates all tables of the app. Flyway runs this file once and remembers it in flyway_schema_history.
-- Never edit this file after it was run; add V2__..., V3__... for later changes.

CREATE TABLE expense_groups (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100)                NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE members (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(50) NOT NULL,
    group_id BIGINT      NOT NULL REFERENCES expense_groups (id),
    CONSTRAINT uk_members_group_name UNIQUE (group_id, name)
);

CREATE TABLE expenses (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id          BIGINT                      NOT NULL REFERENCES expense_groups (id),
    description       VARCHAR(100)                NOT NULL,
    amount_cents      BIGINT                      NOT NULL,
    paid_by_member_id BIGINT                      NOT NULL REFERENCES members (id),
    split_type        VARCHAR(10)                 NOT NULL CHECK (split_type IN ('EQUAL', 'EXACT')),
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE expense_shares (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_id  BIGINT NOT NULL REFERENCES expenses (id),
    member_id   BIGINT NOT NULL REFERENCES members (id),
    share_cents BIGINT NOT NULL,
    CONSTRAINT uk_expense_shares_expense_member UNIQUE (expense_id, member_id)
);

CREATE TABLE payments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id       BIGINT                      NOT NULL REFERENCES expense_groups (id),
    from_member_id BIGINT                      NOT NULL REFERENCES members (id),
    to_member_id   BIGINT                      NOT NULL REFERENCES members (id),
    amount_cents   BIGINT                      NOT NULL,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
